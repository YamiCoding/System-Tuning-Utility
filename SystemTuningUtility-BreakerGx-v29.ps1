# FUNCTION: 14. INPUT QUEUE SIZE & TCP LOW-LATENCY
# =====================================================================
function Invoke-InputQueueAndTcpTweaks {
    param([int]$Option, [switch]$Silent)
    if (-not $Silent) { Clear-Host }

    if ($Option -eq 1) {
        if (-not $Silent) { Write-Host "[1/2] Optimizing Mouse & Keyboard DataQueueSize & Raw Input..." -ForegroundColor Cyan }
        $mouPath = "HKLM:\SYSTEM\CurrentControlSet\Services\mouclass\Parameters"
        $kbdPath = "HKLM:\SYSTEM\CurrentControlSet\Services\kbdclass\Parameters"
        if (!(Test-Path $mouPath)) { New-Item -Path $mouPath -Force -ErrorAction SilentlyContinue | Out-Null }
        if (!(Test-Path $kbdPath)) { New-Item -Path $kbdPath -Force -ErrorAction SilentlyContinue | Out-Null }
        Set-ItemProperty -Path $mouPath -Name "MouseDataQueueSize" -Value 32 -Type DWord -Force -ErrorAction SilentlyContinue
        Set-ItemProperty -Path $kbdPath -Name "KeyboardDataQueueSize" -Value 32 -Type DWord -Force -ErrorAction SilentlyContinue

