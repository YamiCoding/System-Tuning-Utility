        Remove-Item -Path "HKCU:\Software\AMD\CN\Notification" -Recurse -Force -ErrorAction SilentlyContinue
        Remove-Item -Path "HKCU:\Software\AMD\CN\FreeSync" -Recurse -Force -ErrorAction SilentlyContinue
        Remove-Item -Path "HKCU:\Software\AMD\CN\OverlayNotification" -Recurse -Force -ErrorAction SilentlyContinue
        Remove-Item -Path "HKCU:\Software\AMD\CN\VirtualSuperResolution" -Recurse -Force -ErrorAction SilentlyContinue

        $adapterKeys = Get-ChildItem -Path $amdClassPath -ErrorAction SilentlyContinue | Where-Object { $_.PSChildName -match '^\d{4}$' }
        foreach ($key in $adapterKeys) {
            Set-ItemProperty -Path $key.PSPath -Name "KMD_DeLagEnabled" -Value 0 -Type DWord -Force -ErrorAction SilentlyContinue
            Set-ItemProperty -Path $key.PSPath -Name "IsAutoDefault" -Value 1 -Type DWord -Force -ErrorAction SilentlyContinue
            Set-ItemProperty -Path $key.PSPath -Name "IsComponentControl" -Value ([byte[]]@(0,0,0,0)) -Type Binary -Force -ErrorAction SilentlyContinue
        }

        $allSub = Get-ChildItem -Path $amdClassPath -Recurse -ErrorAction SilentlyContinue
        foreach ($key in ($allSub | Where-Object { $_.PSChildName -eq "UMD" })) {
            Set-ItemProperty -Path $key.PSPath -Name "VSyncControl" -Value ([byte[]]@(0x31,0x00,0x00,0x00)) -Type Binary -Force -ErrorAction SilentlyContinue
            Remove-ItemProperty -Path $key.PSPath -Name "TFQ" -ErrorAction SilentlyContinue
            Set-ItemProperty -Path $key.PSPath -Name "Tessellation" -Value ([byte[]]@(0x36,0x00,0x34,0x00,0x00,0x00)) -Type Binary -Force -ErrorAction SilentlyContinue
            Set-ItemProperty -Path $key.PSPath -Name "Tessellation_OPTION" -Value ([byte[]]@(0x30,0x00,0x00,0x00)) -Type Binary -Force -ErrorAction SilentlyContinue
        }

        foreach ($key in ($allSub | Where-Object { $_.PSChildName -eq "power_v1" })) {
            Remove-ItemProperty -Path $key.PSPath -Name "abmlevel" -ErrorAction SilentlyContinue
        }

        Write-Host " -> AMD Radeon defaults restored." -ForegroundColor Green
    }

    if (-not $Silent) { Write-Host "`nDone." -ForegroundColor Green; Pause }
}

