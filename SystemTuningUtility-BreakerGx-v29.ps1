# FUNCTION: 19. STATUS CHECK (CURRENT TWEAK STATE)
# =====================================================================
function Invoke-StatusCheck {
    Clear-Host
    Write-Host "==========================================================" -ForegroundColor Cyan
    Write-Host "           CURRENT SYSTEM TUNING STATUS CHECK             " -ForegroundColor Cyan
    Write-Host "==========================================================" -ForegroundColor Cyan

    # 1. GPU MSI Mode
    $gpuDevices = Get-PnpDevice -Class Display -ErrorAction SilentlyContinue
    foreach ($gpu in $gpuDevices) {
        $regPath = "Registry::HKLM\SYSTEM\CurrentControlSet\Enum\$($gpu.InstanceId)\Device Parameters\Interrupt Management\MessageSignaledInterruptProperties"
        $msiVal = (Get-ItemProperty -Path $regPath -Name "MSISupported" -ErrorAction SilentlyContinue).MSISupported
        Write-Host ("GPU MSI Mode ({0}): {1}" -f $gpu.FriendlyName, $(if ($msiVal -eq 1) { "Enabled (1)" } else { "Default/Off ($msiVal)" })) -ForegroundColor White
    }

    # 2. HAGS
    $hagsVal = (Get-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Control\GraphicsDrivers" -Name "HwSchMode" -ErrorAction SilentlyContinue).HwSchMode
    Write-Host ("HAGS (HwSchMode)           : {0}" -f $(if ($hagsVal -eq 2) { "Enabled (2)" } else { "Default/Off ($hagsVal)" })) -ForegroundColor White

    # 3. Win32PrioritySeparation
    $prioVal = (Get-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Control\PriorityControl" -Name "Win32PrioritySeparation" -ErrorAction SilentlyContinue).Win32PrioritySeparation
    Write-Host ("Win32PrioritySeparation    : 0x{0:X} ({0})" -f $prioVal) -ForegroundColor White

    # 4. Active Power Plan
    $activePlan = (powercfg /getactivescheme) -replace 'Power Scheme GUID:\s*', ''
    Write-Host "Active Power Plan          : $activePlan" -ForegroundColor White

    # 5. Timer Resolution Service (STR)
    $strSvc = Get-Service -Name "STR" -ErrorAction SilentlyContinue
    Write-Host ("STR Timer Service          : {0}" -f $(if ($strSvc) { "$($strSvc.Status) [$($strSvc.StartType)]" } else { "Not Installed" })) -ForegroundColor White

    # 6. SysMain
    $sysMain = Get-Service -Name "SysMain" -ErrorAction SilentlyContinue
    Write-Host ("SysMain (Superfetch)       : {0}" -f $(if ($sysMain) { "$($sysMain.Status) [$($sysMain.StartType)]" } else { "Not Found" })) -ForegroundColor White

    # 7. BITS & Xbox Gaming Services
    $bitsSvc = Get-Service -Name "BITS" -ErrorAction SilentlyContinue
    $gsSvc = Get-Service -Name "GamingServices" -ErrorAction SilentlyContinue
    Write-Host ("BITS Service               : {0}" -f $(if ($bitsSvc) { "$($bitsSvc.Status) [$($bitsSvc.StartType)]" } else { "Not Found" })) -ForegroundColor White
    Write-Host ("Xbox GamingServices        : {0}" -f $(if ($gsSvc) { "$($gsSvc.Status) [$($gsSvc.StartType)]" } else { "Not Installed" })) -ForegroundColor White

    # 8. Input Queue Size
    $mouQ = (Get-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Services\mouclass\Parameters" -Name "MouseDataQueueSize" -ErrorAction SilentlyContinue).MouseDataQueueSize
    $kbdQ = (Get-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Services\kbdclass\Parameters" -Name "KeyboardDataQueueSize" -ErrorAction SilentlyContinue).KeyboardDataQueueSize
