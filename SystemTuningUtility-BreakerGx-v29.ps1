# FUNCTION: 12. MMAGENT & MEMORY MANAGEMENT
# =====================================================================
function Invoke-MMAgentConfig {
    param([int]$Option, [switch]$Silent)
    if (-not $Silent) { Clear-Host }

    switch ($Option) {
        1 {
            Write-Host "Disabling Memory Management Overheads (SysMain & Prefetch)..." -ForegroundColor Cyan

            $pfKey = "HKLM:\SYSTEM\CurrentControlSet\Control\Session Manager\Memory Management\PrefetchParameters"
            if (Test-Path $pfKey) {
                Set-ItemProperty -Path $pfKey -Name "EnablePrefetcher" -Value 0 -Type DWord -Force
                Set-ItemProperty -Path $pfKey -Name "EnableSuperfetch" -Value 0 -Type DWord -Force
            }

            Stop-Service -Name "SysMain" -Force -ErrorAction SilentlyContinue
            Set-Service -Name "SysMain" -StartupType Disabled -ErrorAction SilentlyContinue

            try { Disable-MMAgent -ApplicationLaunchPrefetching -ErrorAction Stop } catch {}
            try { Disable-MMAgent -ApplicationPreLaunch -ErrorAction Stop } catch {}
            try { Set-MMAgent -MaxOperationAPIFiles 1 -ErrorAction Stop } catch {}
            try { Disable-MMAgent -PageCombining -ErrorAction Stop } catch {}

            if (-not $Silent) { Write-Host "MMAgent & Prefetch Features: Successfully Disabled (Off)" -ForegroundColor Green; Pause }
        }
        2 {
            Write-Host "Restoring Memory Management Features to Windows Default..." -ForegroundColor Yellow

            $pfKey = "HKLM:\SYSTEM\CurrentControlSet\Control\Session Manager\Memory Management\PrefetchParameters"
            if (Test-Path $pfKey) {
                Set-ItemProperty -Path $pfKey -Name "EnablePrefetcher" -Value 3 -Type DWord -Force
                Set-ItemProperty -Path $pfKey -Name "EnableSuperfetch" -Value 3 -Type DWord -Force
            }

            Set-Service -Name "SysMain" -StartupType Automatic -ErrorAction SilentlyContinue
            Start-Service -Name "SysMain" -ErrorAction SilentlyContinue

            try { Enable-MMAgent -ApplicationLaunchPrefetching -ErrorAction Stop } catch {}
            try { Enable-MMAgent -ApplicationPreLaunch -ErrorAction Stop } catch {}
            try { Set-MMAgent -MaxOperationAPIFiles 512 -ErrorAction Stop } catch {}
            try { Enable-MMAgent -MemoryCompression -ErrorAction Stop } catch {}
            try { Enable-MMAgent -OperationAPI -ErrorAction Stop } catch {}
            try { Disable-MMAgent -PageCombining -ErrorAction Stop } catch {}

            if (-not $Silent) { Write-Host "MMAgent Features: Restored to Default" -ForegroundColor Green; Pause }
        }
        3 {
            Write-Host "Checking Current Memory Management & MMAgent State:`n" -ForegroundColor Cyan
            
            $sysMain = Get-Service -Name "SysMain" -ErrorAction SilentlyContinue
            Write-Host "SysMain (Superfetch) Service: $($sysMain.Status) [Startup: $($sysMain.StartType)]" -ForegroundColor White

            $pfKey = "HKLM:\SYSTEM\CurrentControlSet\Control\Session Manager\Memory Management\PrefetchParameters"
            $pfVal = (Get-ItemProperty -Path $pfKey -Name "EnablePrefetcher" -ErrorAction SilentlyContinue).EnablePrefetcher
            Write-Host "EnablePrefetcher Registry Value: $pfVal (0 = Disabled, 3 = Default)" -ForegroundColor White

            Write-Host "`nGet-MMAgent Output:" -ForegroundColor Cyan
            try {
                Get-MMAgent
            } catch {
                Write-Host "MMAgent querying is currently uninitialized or restricted by Windows." -ForegroundColor Yellow
            }

            Pause
        }
    }
}

