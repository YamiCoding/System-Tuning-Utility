function Invoke-MsiMode {
    param([int]$State, [switch]$Silent)
    if (-not $Silent) { Clear-Host }
    Write-Host "Configuring GPU MSI Mode..." -ForegroundColor Cyan
    $gpuDevices = Get-PnpDevice -Class Display -ErrorAction SilentlyContinue
    foreach ($gpu in $gpuDevices) {
        $instanceID = $gpu.InstanceId
        $msiPath = "HKLM\SYSTEM\CurrentControlSet\Enum\$instanceID\Device Parameters\Interrupt Management\MessageSignaledInterruptProperties"
        reg add "$msiPath" /v "MSISupported" /t REG_DWORD /d "$State" /f | Out-Null
    }

    if (-not $Silent) {
        Write-Host "`nCurrent GPU MSI Configuration:" -ForegroundColor Cyan
        foreach ($gpu in $gpuDevices) {
            $instanceID = $gpu.InstanceId
            $regPath = "Registry::HKLM\SYSTEM\CurrentControlSet\Enum\$instanceID\Device Parameters\Interrupt Management\MessageSignaledInterruptProperties"
            try {
                $msiSupported = Get-ItemProperty -Path $regPath -Name "MSISupported" -ErrorAction Stop
                Write-Output "$instanceID"
                Write-Output "MSISupported: $($msiSupported.MSISupported)"
            } catch {
                Write-Output "$instanceID"
                Write-Output "MSISupported: Not found or error accessing registry."
            }
        }
        Write-Host "`nDone." -ForegroundColor Green
        Pause
    }
}

function Invoke-MpoOptimizations {
    param([bool]$Enable, [switch]$Silent)
    if (-not $Silent) { Clear-Host }
    if ($Enable) {
        Write-Host "Enabling MPO & Windowed Optimizations..." -ForegroundColor Cyan
        cmd /c "reg delete `"HKLM\SOFTWARE\Microsoft\Windows\Dwm`" /v `"OverlayTestMode`" /f >nul 2>&1"
        reg add "HKCU\Software\Microsoft\DirectX\UserGpuPreferences" /v "DirectXUserGlobalSettings" /t REG_SZ /d "VRROptimizeEnable=0;SwapEffectUpgradeEnable=1;" /f | Out-Null
    } else {
        Write-Host "Disabling MPO & Windowed Optimizations..." -ForegroundColor Yellow
        reg add "HKLM\SOFTWARE\Microsoft\Windows\Dwm" /v "OverlayTestMode" /t REG_DWORD /d "5" /f | Out-Null
        reg add "HKCU\Software\Microsoft\DirectX\UserGpuPreferences" /v "DirectXUserGlobalSettings" /t REG_SZ /d "VRROptimizeEnable=0;SwapEffectUpgradeEnable=0;" /f | Out-Null
    }
    if (-not $Silent) { Write-Host "Done." -ForegroundColor Green; Pause }
}

