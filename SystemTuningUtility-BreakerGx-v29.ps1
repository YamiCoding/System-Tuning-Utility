        Set-ItemProperty -Path "HKCU:\Control Panel\Mouse" -Name "MouseThreshold1" -Value "0" -Type String -Force -ErrorAction SilentlyContinue
        Set-ItemProperty -Path "HKCU:\Control Panel\Mouse" -Name "MouseThreshold2" -Value "0" -Type String -Force -ErrorAction SilentlyContinue

        if (-not $Silent) { Write-Host "[2/2] Disabling Nagle's Algorithm (TCP NoDelay) & RSC on Active Adapters..." -ForegroundColor Cyan }
        $interfacesPath = "HKLM:\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces"
        Get-ChildItem -Path $interfacesPath -ErrorAction SilentlyContinue | ForEach-Object {
            Set-ItemProperty -Path $_.PSPath -Name "TcpAckFrequency" -Value 1 -Type DWord -Force -ErrorAction SilentlyContinue
            Set-ItemProperty -Path $_.PSPath -Name "TCPNoDelay" -Value 1 -Type DWord -Force -ErrorAction SilentlyContinue
            Set-ItemProperty -Path $_.PSPath -Name "TcpDelAckTicks" -Value 0 -Type DWord -Force -ErrorAction SilentlyContinue
        }
        Disable-NetAdapterRsc -Name "*" -ErrorAction SilentlyContinue | Out-Null

        if (-not $Silent) { Write-Host " -> Input Queue Size & TCP Low-Latency Applied." -ForegroundColor Green; Pause }
    } else {
        if (-not $Silent) { Write-Host "Restoring Input Queue & TCP Defaults..." -ForegroundColor Yellow }
        Remove-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Services\mouclass\Parameters" -Name "MouseDataQueueSize" -ErrorAction SilentlyContinue
        Remove-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Services\kbdclass\Parameters" -Name "KeyboardDataQueueSize" -ErrorAction SilentlyContinue

        $interfacesPath = "HKLM:\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces"
        Get-ChildItem -Path $interfacesPath -ErrorAction SilentlyContinue | ForEach-Object {
            Remove-ItemProperty -Path $_.PSPath -Name "TcpAckFrequency" -ErrorAction SilentlyContinue
            Remove-ItemProperty -Path $_.PSPath -Name "TCPNoDelay" -ErrorAction SilentlyContinue
            Remove-ItemProperty -Path $_.PSPath -Name "TcpDelAckTicks" -ErrorAction SilentlyContinue
        }
        Enable-NetAdapterRsc -Name "*" -ErrorAction SilentlyContinue | Out-Null
        if (-not $Silent) { Write-Host " -> Defaults Restored." -ForegroundColor Green; Pause }
    }
}

