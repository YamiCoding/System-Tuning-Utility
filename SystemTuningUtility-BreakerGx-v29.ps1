# FUNCTION: 13. HAGS, NVMe CACHE & SERVICES
# =====================================================================
function Invoke-HagsNvmeAndServices {
    param([int]$Option, [switch]$Silent)
    if (-not $Silent) { Clear-Host }

    if ($Option -eq 1) {
        Write-Host "[1/3] Enabling Hardware-Accelerated GPU Scheduling (HAGS)..." -ForegroundColor Cyan
        try {
            $gfxPath = "HKLM:\SYSTEM\CurrentControlSet\Control\GraphicsDrivers"
            if (!(Test-Path $gfxPath)) { New-Item -Path $gfxPath -Force | Out-Null }
            Set-ItemProperty -Path $gfxPath -Name "HwSchMode" -Value 2 -Type DWord -Force
            Write-Host " -> HAGS enabled (HwSchMode = 2)." -ForegroundColor Green
        } catch {
            Write-Host " -> Error enabling HAGS: $_" -ForegroundColor Red
        }

        Write-Host "[2/3] Configuring NVMe Write Caching & Buffer Flushing..." -ForegroundColor Cyan
        $nvmeDevices = Get-PnpDevice -Class DiskDrive -ErrorAction SilentlyContinue | Where-Object { $_.InstanceId -match "NVME|SCSI\\DISK&VEN_NVME" -or $_.FriendlyName -match "NVMe" }
        if (!$nvmeDevices) {
            Write-Host " -> No NVMe drives detected via PnP." -ForegroundColor Yellow
        }
        foreach ($disk in $nvmeDevices) {
            try {
                $regSubKey = "SYSTEM\CurrentControlSet\Enum\$($disk.InstanceId)\Device Parameters\Disk"
                $diskParamPath = "HKLM:\$regSubKey"

                $key = [Microsoft.Win32.Registry]::LocalMachine.CreateSubKey($regSubKey, [Microsoft.Win32.RegistryKeyPermissionCheck]::ReadWriteSubTree)
                $acl = $key.GetAccessControl()
                $rule = New-Object System.Security.AccessControl.RegistryAccessRule("Administrators", "FullControl", "ContainerInherit,ObjectInherit", "None", "Allow")
                $acl.SetAccessRule($rule)
                $key.SetAccessControl($acl)
                $key.Close()

                Set-ItemProperty -Path $diskParamPath -Name "UserWriteCacheSetting" -Value 1 -Type DWord -Force
                Set-ItemProperty -Path $diskParamPath -Name "CacheIsPowerProtected" -Value 1 -Type DWord -Force
                Write-Host " -> Applied to: $($disk.FriendlyName)" -ForegroundColor Green
            } catch {
                Write-Host " -> Failed on $($disk.FriendlyName): $_" -ForegroundColor Red
            }
        }

        Write-Host "[3/3] Configuring Windows Services (Preserving BITS & Xbox Services)..." -ForegroundColor Cyan
        sc.exe config BITS start= delayed-auto | Out-Null
        sc.exe config TermService start= demand | Out-Null
        sc.exe stop SysMain | Out-Null
        sc.exe config SysMain start= disabled | Out-Null
        $xboxServices = @("XblAuthManager", "XblGameSave", "XboxNetApiSvc", "XboxGipSvc", "GamingServices", "GamingServicesNet")
        foreach ($svc in $xboxServices) {
            if (Get-Service -Name $svc -ErrorAction SilentlyContinue) {
                sc.exe config $svc start= demand | Out-Null
            }
        }
        Write-Host " -> Services updated safely (BITS & Xbox services preserved, SysMain disabled)." -ForegroundColor Green
    } else {
        Write-Host "Restoring HAGS, NVMe Cache & Services Defaults..." -ForegroundColor Yellow
        $nvmeDevices = Get-PnpDevice -Class DiskDrive -ErrorAction SilentlyContinue | Where-Object { $_.InstanceId -match "NVME|SCSI\\DISK&VEN_NVME" -or $_.FriendlyName -match "NVMe" }
        foreach ($disk in $nvmeDevices) {
            $diskParamPath = "HKLM:\SYSTEM\CurrentControlSet\Enum\$($disk.InstanceId)\Device Parameters\Disk"
            Remove-ItemProperty -Path $diskParamPath -Name "CacheIsPowerProtected" -ErrorAction SilentlyContinue
        }
        sc.exe config BITS start= delayed-auto | Out-Null
        sc.exe config SysMain start= auto | Out-Null
        sc.exe start SysMain | Out-Null
        Write-Host " -> Defaults restored." -ForegroundColor Green
    }

    if (-not $Silent) { Write-Host "`nDone." -ForegroundColor Green; Pause }
}

