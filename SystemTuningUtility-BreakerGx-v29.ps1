                Invoke-ExtraTweaksAction -Id 5 -Silent
                Invoke-ExtraTweaksAction -Id 6 -Silent
                Invoke-ExtraTweaksAction -Id 7 -Silent
                Invoke-ExtraTweaksAction -Id 8 -Silent
                Invoke-ExtraTweaksAction -Id 9 -Silent
                Invoke-ExtraTweaksAction -Id 10 -Silent
                Invoke-ExtraTweaksAction -Id 11 -Silent
                Invoke-ExtraTweaksAction -Id 12 -Silent
                Invoke-ExtraTweaksAction -Id 13 -Silent
                Invoke-ExtraTweaksAction -Id 14 -Silent
                Invoke-ExtraTweaksAction -Id 15 -Silent
                Write-Host "`nAll Extra Tweaks applied successfully!" -ForegroundColor Green
                Pause
            }
            "R" {
                Clear-Host
                Write-Host "Reverting All Extra Tweaks (1-15) to Windows Defaults..." -ForegroundColor Yellow
                for ($k = 1; $k -le 15; $k++) {
                    Invoke-ExtraTweaksAction -Id $k -Revert -Silent
                }
                Write-Host "`nAll Extra Tweaks reverted to defaults!" -ForegroundColor Green
                Pause
            }
            default {
                $num = 0
                if ([int]::TryParse($subChoice, [ref]$num) -and $num -ge 1 -and $num -le 9) {
                    Clear-Host
                    Write-Host "1. Apply Option #$num"
                    Write-Host "2. Revert Option #$num to Default"
                    $act = Read-Host "Choice (1-2)"
                    if ($act -in @("1", "2")) {
                        $isRev = ($act -eq "2")
                        if ($num -eq 7) {
                            for ($pid = 7; $pid -le 13; $pid++) {
                                Invoke-ExtraTweaksAction -Id $pid -Revert:$isRev -Silent
                            }
                            Write-Host ("Done (" + $(if ($isRev) { "Reverted" } else { "Applied" }) + ").") -ForegroundColor Green
                            Pause
                        } elseif ($num -eq 8) {
                            Invoke-ExtraTweaksAction -Id 14 -Revert:$isRev
                        } elseif ($num -eq 9) {
                            Invoke-ExtraTweaksAction -Id 15 -Revert:$isRev
                        } else {
                            Invoke-ExtraTweaksAction -Id $num -Revert:$isRev
                        }
                    }
                } else {
                    Write-Host "Invalid choice." -ForegroundColor Red
                    Start-Sleep -Seconds 1
                }
            }
        }
    }
}


